package com.p2ppayment.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Entity
@Table(name = "notifications")
public class Notification {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @Column(nullable = false, length = 50)
    private String type;

    @Column(nullable = false, length = 255)
    private String title;

    @Column(nullable = false, columnDefinition = "TEXT")
    private String message;

    @Column(nullable = false)
    @Builder.Default
    private Boolean isRead = false;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "related_transaction_id", nullable = true)
    private Transaction relatedTransaction;

    @Column(nullable = false)
    private LocalDateTime createdAt;

    @PrePersist
    protected void onCreate() {
        if (createdAt == null) {
            createdAt = LocalDateTime.now();
        }
        if (isRead == null) {
            isRead = false;
        }
    }

    public enum Type {
        TRANSFER_INITIATED("Transfer initiated"),
        TRANSFER_SETTLED("Transfer settled"),
        TRANSFER_FAILED("Transfer failed"),
        DAILY_LIMIT_EXCEEDED("Daily limit exceeded"),
        FRAUD_ALERT_HIGH_VALUE("High-value fraud alert"),
        ACCOUNT_LOCKED("Account locked"),
        ACCOUNT_UNLOCKED("Account auto-unlocked"),
        WALLET_TOP_UP("Wallet top-up successful"),
        AUTO_RELOAD_SUCCESS("Auto Reload successful"),
        AUTO_RELOAD_FAILED("Auto Reload failed"),
        DEMO_FUNDS_ADDED("Demo funds added");

        private final String displayName;

        Type(String displayName) {
            this.displayName = displayName;
        }

        public String getDisplayName() {
            return displayName;
        }
    }
}
